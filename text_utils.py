# -*- coding: utf-8 -*-
"""
نرمال‌سازی متن فارسی/عربی برای جستجوی قابل‌اعتماد.

داده‌های قدیمی این پروژه از یک فایل Access قدیمی وارد شده‌اند و برخی
حروف با نویسه‌ی عربی به‌جای فارسی ذخیره شده‌اند — مثلاً «ي» عربی
(U+064A) به‌جای «ی» فارسی (U+06CC)، یا «ك» عربی (U+0643) به‌جای «ک»
فارسی (U+06A9). این دو کاراکتر ظاهراً یکسان به نظر می‌رسند ولی از نظر
کامپیوتر کاملاً متفاوت‌اند، پس جستجوی معمولی (یا خودِ مرورگر در
datalist) نمی‌تواند بین آن‌ها تطبیق بدهد. این تابع هر دو را قبل از
مقایسه به یک شکل استاندارد (فارسی) تبدیل می‌کند.
"""

_CHAR_MAP = {
    "\u064a": "\u06cc",  # ي عربی -> ی فارسی
    "\u0649": "\u06cc",  # ى (الف مقصوره) -> ی فارسی
    "\u0643": "\u06a9",  # ك عربی -> ک فارسی
    "\u0629": "\u0647",  # ة -> ه
    "\u0623": "\u0627",  # أ -> ا
    "\u0625": "\u0627",  # إ -> ا
    "\u0622": "\u0627",  # آ -> ا (فقط برای جستجو، نه نمایش)
    "\u06c0": "\u0647",  # ۀ -> ه
}


def normalize_fa(text: str) -> str:
    if not text:
        return ""
    result = []
    for ch in text:
        result.append(_CHAR_MAP.get(ch, ch))
    normalized = "".join(result)
    normalized = " ".join(normalized.split())  # چند فاصله پشت‌سرهم -> یک فاصله
    return normalized.strip().lower()
